CREATE TABLE IF NOT EXISTS official_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT NULL,
    category VARCHAR(100) NOT NULL DEFAULT 'General',
    current_version INT NOT NULL DEFAULT 1,
    current_file_name VARCHAR(255) NOT NULL,
    current_file_path VARCHAR(500) NOT NULL,
    current_file_size BIGINT NOT NULL DEFAULT 0,
    current_content_type VARCHAR(100) NOT NULL DEFAULT 'application/pdf',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_visible BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INT NOT NULL DEFAULT 0,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    deleted_by BIGINT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE NULL
);

CREATE TABLE IF NOT EXISTS official_template_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    official_template_id BIGINT NOT NULL,
    version_number INT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    file_size BIGINT NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    change_notes TEXT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    uploaded_by BIGINT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_visible BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INT NOT NULL DEFAULT 0,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    deleted_by BIGINT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT fk_official_template_versions_template 
        FOREIGN KEY (official_template_id) REFERENCES official_templates(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_official_templates_code ON official_templates(code);
CREATE INDEX IF NOT EXISTS ix_official_templates_is_active ON official_templates(is_active);
CREATE INDEX IF NOT EXISTS ix_official_templates_category ON official_templates(category);
CREATE INDEX IF NOT EXISTS ix_official_template_versions_template_id ON official_template_versions(official_template_id);
CREATE INDEX IF NOT EXISTS ix_official_template_versions_version ON official_template_versions(official_template_id, version_number);
